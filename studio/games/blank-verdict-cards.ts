// Every card in Blank Verdict, written for this game and nothing else. Prompts have one gap,
// written ___, and answers are short noun phrases that fit any gap, so a clash is the joke. "family"
// cards are clean and silly; "party" cards are rude and petty and never hateful, sexual or about
// anyone's body, race, religion or sexuality. A party room plays with all of them, a family room with
// the family cards only. Nothing here may sit inside another card's text, or the leak check could
// mistake one for another; the kit's checks test that, the language filter and the room's rules.

import type { AnswerCard, PromptCard } from "../kits/hand.ts";

/**
 * Builds cards from lines, numbering them so each has a stable id.
 * @param prefix the id prefix, such as "fa" for family answers.
 * @param tone which room the cards are for.
 * @param texts the card texts, in order.
 * @returns the cards.
 */
function cards(prefix: string, tone: "family" | "party", texts: readonly string[]): AnswerCard[] {
    return texts.map((text: string, index: number): AnswerCard => ({ id: `${prefix}${String(index + 1).padStart(3, "0")}`, text, tone }));
}

